"""Ship 2K colour, normal and roughness maps for the texture sets seen close up (every tiling surface: the sets with a
displacement map, plus the character fabrics), next to their 1K maps, and write src/graphics/materials/hires.ts.
High and Ultra load the 2K maps (`textureResolution: '2k'`); phones and the lower presets keep 1K.
ImageMagick does the encoding (this container's PIL cannot write JPEG):   python3 tools/assets/ship_2k.py"""
import os, subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PUB = os.path.join(ROOT, 'public', 'assets', 'textures', 'pbr')
PH = os.path.join(ROOT, 'vendor', 'polyhaven', 'textures')
FABRICS = {'cotton_jersey', 'denim_fabric', 'fabric_leather_02', 'hessian_230', 'bi_stretch', 'scuba_suede', 'stretch_poplin',
           'painted_concrete', 'dirty_carpet'}
ARGS = {'diff': ['-quality', '88'], 'nor_gl': ['-sampling-factor', '4:4:4', '-quality', '92'], 'rough': ['-colorspace', 'Gray', '-quality', '88']}
done = []
for tid in sorted(os.listdir(PUB)):
    files = os.listdir(os.path.join(PUB, tid))
    if not (any(f.endswith('_disp.jpg') for f in files) or tid in FABRICS):
        continue
    ok = True
    for m, args in ARGS.items():
        src = next((p for p in (os.path.join(PH, tid, f'{tid}_{m}_2k.{e}') for e in ('jpg', 'png')) if os.path.exists(p)), None)
        dst = os.path.join(PUB, tid, f'{tid}_{m}_2k.jpg')
        if not src:
            ok = False
            continue
        if not os.path.exists(dst):
            subprocess.run(['convert', src, *args, '-strip', dst], check=True)
    if ok:
        done.append(tid)
with open(os.path.join(ROOT, 'src', 'graphics', 'materials', 'hires.ts'), 'w') as f:
    f.write('// generated by tools/assets/ship_2k.py: texture sets that ship 2K colour, normal and roughness maps\n')
    f.write('export const HIRES_SETS = new Set<string>([\n' + ''.join(f"  '{t}',\n" for t in done) + ']);\n')
print(len(done), 'sets at 2K:', ', '.join(done))
