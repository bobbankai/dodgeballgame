"""Ship 1k ambient-occlusion maps for every Poly Haven set the game uses and write src/rendering/aosets.ts (the sets that have one).
The engine multiplies the albedo by the AO map exactly as the Blender material does (garments.pbr: multiply, factor 0.8), so what
was reviewed in Cycles is what the game shows.   python3 tools/assets/ship_ao.py"""
import os

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PUB = os.path.join(ROOT, 'public', 'assets', 'textures', 'pbr')
PH = os.path.join(ROOT, 'vendor', 'polyhaven', 'textures')
have = []
for tid in sorted(os.listdir(PUB)):
    src = os.path.join(PH, tid, f'{tid}_ao_2k.jpg')
    dst = os.path.join(PUB, tid, f'{tid}_ao.jpg')
    if os.path.exists(src):
        if not os.path.exists(dst):
            Image.open(src).convert('L').resize((1024, 1024), Image.LANCZOS).save(dst, quality=90)
        have.append(tid)
with open(os.path.join(ROOT, 'src', 'rendering', 'aosets.ts'), 'w') as f:
    f.write('// generated by tools/assets/ship_ao.py: texture sets that ship an ambient-occlusion map\n')
    f.write('export const AO_SETS = new Set<string>([\n' + ''.join(f"  '{t}',\n" for t in have) + ']);\n')
print(len(have), 'sets with AO:', ', '.join(have))
